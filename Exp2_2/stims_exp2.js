// Pilot uses fail2 and fail3. Use [1, 2, 3] for all positions.
const EXP2_ENABLED_FAILS = new Set([2, 3]);

// Rotate the F1_n ordinal across items. Each participant starts at a random
// offset, so the same item can use first/second/third across participants.
const EXP2_F1_ROTATION_OFFSET = Math.floor(Math.random() * 3);

function expandExp2Fillers(item) {
    const ordinals = ["첫 번째", "두 번째", "세 번째"];
    const itemNumber = Number(item.item.replace(/\D/g, ""));
    if (!Number.isInteger(itemNumber) || itemNumber < 1 ||
        typeof item.f1_n_template !== "string" ||
        !item.f1_n_template.includes("{N}")) {
    throw new Error(`Invalid F1_n template or item ID: ${item.item}`);
  }
    const f1_n_position = ((itemNumber - 1 + EXP2_F1_ROTATION_OFFSET) % 3) + 1;
    const failed = item.fail;
    const succeededPositions = [1, 2, 3].filter(position => position !== failed);
    // Randomly select one of the two successful objects
    const succeeded = succeededPositions[Math.floor(Math.random() * succeededPositions.length)];
    const sentence = (position, verb) => `${item.filler_subject} ${ordinals[position - 1]} ${item.filler_object} ${verb}.`;
    return {
        ...item,
        // All three A events happened. "Only Nth A" is always false.
        f1_n_position,
        f1_n: item.f1_n_template.replace("{N}", ordinals[f1_n_position - 1]),
        f2_y: sentence(succeeded, item.filler_positive),
        f2_y_correct: "예",
        f2_n: sentence(failed, item.filler_positive),
        f2_n_correct: "아니오",
        f3_LFN_y: sentence(failed, item.filler_negative_LFN),
        f3_LFN_y_correct: "예",
        f3_LFN_n: sentence(succeeded, item.filler_negative_LFN),
        f3_LFN_n_correct: "아니오",
        f3_SFN_y: sentence(failed, item.filler_negative_SFN),
        f3_SFN_y_correct: "예",
        f3_SFN_n: sentence(succeeded, item.filler_negative_SFN),
        f3_SFN_n_correct: "아니오",
    };
}

window.EXP2_STIMULI = EXP2_ITEM_DEFINITIONS.flatMap(
  ({ variants, ...common }) => variants
    .filter(v => EXP2_ENABLED_FAILS.has(v.fail))
    .map(v => expandExp2Fillers({ ...common, ...v }))
);
